package practice;

/**
 * Бинарный поиск — это алгоритм поиска элемента в отсортированном массиве, который работает за O(log n),
 * последовательно деля область поиска пополам.
 *
 * 🧠 Как работает
 * Берём середину массива.
 *
 * Сравниваем искомое значение с элементом в середине:
 *
 * Если равно — нашли.
 *
 * Если искомое меньше — ищем в левой половине.
 *
 * Если больше — ищем в правой половине.
 *
 * Повторяем, пока не найдём или пока область поиска не станет пустой.
 *
 * Важно: массив должен быть отсортирован, иначе алгоритм не работает.
 *
 * Переполнение при вычислении mid
 * (left + right) / 2 может переполниться для больших left и right.
 * Правильно: left + (right - left) / 2.
 *
 * Ошибка в условии цикла
 * while (left <= right) — правильно. Если написать <, можно пропустить последний элемент.
 *
 * Неправильное обновление границ
 * left = mid + 1, right = mid - 1 — обязательно, иначе бесконечный цикл.
 */
public class BinarySearchLesson {
    public static void main(String[] args) {
        int[] nums = {1,2,3,4,5,6,7};
        int target = 8;
        System.out.println(search(nums, target));
    }

    public static int search(int[] nums, int target) {

        int l = 0;
        int r = nums.length - 1;

        while (l <= r) {
            int mid = l + (r - l) / 2;
            if (nums[mid] == target) {
                return mid;
            }
            if (nums[mid] < target) {
                l = mid + 1;
            }
            else
                r = mid - 1;
        }
        return - 1;
    }
}
